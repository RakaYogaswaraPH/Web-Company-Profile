import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const OUT_DIR = path.join(ROOT, "out");
const PUBLIC_SW = path.join(ROOT, "public/sw.js");
const OUT_SW = path.join(OUT_DIR, "sw.js");

function getFilesRecursively(dir, baseDir = dir) {
  let results = [];
  if (!fs.existsSync(dir)) return results;
  const list = fs.readdirSync(dir);
  for (const file of list) {
    const fullPath = path.join(dir, file);
    const stat = fs.statSync(fullPath);
    if (stat && stat.isDirectory()) {
      results = results.concat(getFilesRecursively(fullPath, baseDir));
    } else {
      const relPath = "/" + path.relative(baseDir, fullPath).replace(/\\/g, "/");
      results.push(relPath);
    }
  }
  return results;
}

function generateSW() {
  console.log("Generating service worker...");

  const hash = crypto.randomBytes(6).toString("hex");
  const CACHE_NAME = `jamparing-cache-${hash}`;

  const precacheUrls = [
    "/",
    "/offline.html",
    "/icons/icon-192.png",
    "/icons/icon-512.png",
    "/icons/icon-maskable-512.png",
    "/icons/apple-touch-icon.png",
    "/icons/favicon-32x32.png",
    "/images/brands/logo.webp",
  ];

  if (fs.existsSync(OUT_DIR)) {
    const allOutFiles = getFilesRecursively(OUT_DIR);
    const staticJsCss = allOutFiles.filter(
      (f) =>
        f.startsWith("/_next/static/") &&
        (f.endsWith(".js") || f.endsWith(".css"))
    );
    precacheUrls.push(...staticJsCss.slice(0, 15));
  }

  const uniquePrecache = Array.from(new Set(precacheUrls));

  const swTemplate = `// Service Worker Generated by scripts/build-sw.mjs
const CACHE_NAME = "${CACHE_NAME}";
const PRECACHE_URLS = ${JSON.stringify(uniquePrecache, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(PRECACHE_URLS);
    }).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames.map((name) => {
          if (name !== CACHE_NAME) {
            return caches.delete(name);
          }
        })
      );
    }).then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);

  // Only handle GET requests with same-origin
  if (request.method !== "GET" || url.origin !== self.location.origin) {
    return;
  }

  // HTML / Navigation requests: Network-first, fallback to cache, then offline.html
  if (request.mode === "navigate" || request.headers.get("accept")?.includes("text/html")) {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response && response.status === 200) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, clone));
          }
          return response;
        })
        .catch(async () => {
          const cached = await caches.match(request);
          if (cached) return cached;
          const offline = await caches.match("/offline.html");
          return offline || Response.error();
        })
    );
    return;
  }

  // Static assets (/_next/static/* or /images/* or /icons/*): Cache-first
  if (url.pathname.startsWith("/_next/static/") || url.pathname.startsWith("/images/") || url.pathname.startsWith("/icons/")) {
    event.respondWith(
      caches.match(request).then((cachedResponse) => {
        if (cachedResponse) {
          return cachedResponse;
        }
        return fetch(request).then((networkResponse) => {
          if (networkResponse && networkResponse.status === 200) {
            const clone = networkResponse.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, clone));
          }
          return networkResponse;
        });
      })
    );
    return;
  }

  // Default: Network with cache fallback
  event.respondWith(
    fetch(request).catch(() => caches.match(request))
  );
});
`;

  fs.writeFileSync(PUBLIC_SW, swTemplate, "utf-8");
  console.log("Written service worker to:", PUBLIC_SW);

  if (fs.existsSync(OUT_DIR)) {
    fs.writeFileSync(OUT_SW, swTemplate, "utf-8");
    console.log("Written service worker to:", OUT_SW);
  }
}

generateSW();
